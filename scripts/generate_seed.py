#!/usr/bin/env python3
"""Generate seed rows for the two implementation tables from udm_schema.json.

The schema names, on each vocabulary column, the value group it draws from
and the codes the specification recommends. Constraints and derivation
rules depend on those codes existing ("the role resolves to canonical PI").
This script writes them as INSERT statements so a new database is usable
right after the DDL runs:

  AllowedValues   one row per recommended code in each value group, with
                  Canonical_Value_Code equal to the code. An institution
                  adds its own codes and labels beside these.
  BudgetCategory  the SF-424 R&R budget line categories, which the schema
                  describes but does not list.

No other table is touched. This is reference data, not sample data: no
awards, people, or proposals. A reference implementation under the code
license, not part of the standard.

Usage:
  generate_seed.py --dialect mysql
  generate_seed.py --dialect postgresql --modules governance
  generate_seed.py --dialect postgresql --all-modules

Output goes to stdout. Dependency-free.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

SCHEMA_PATH = Path(__file__).resolve().parent.parent / "udm_schema.json"
SOURCE_SYSTEM = "UDM"

DIALECTS = {
    "mysql": {"quote": lambda n: f"`{n}`", "now": "CURRENT_TIMESTAMP", "true": "TRUE", "false": "FALSE"},
    "postgresql": {"quote": lambda n: f'"{n}"', "now": "CURRENT_TIMESTAMP", "true": "TRUE", "false": "FALSE"},
}

# SF-424 R&R budget categories, in form order. (code, name, is_direct_cost)
BUDGET_CATEGORIES = [
    ("SR_PERSONNEL", "Senior/Key Personnel", True),
    ("OTH_PERSONNEL", "Other Personnel", True),
    ("FRINGE", "Fringe Benefits", True),
    ("EQUIPMENT", "Equipment", True),
    ("TRAVEL", "Travel", True),
    ("PARTICIPANT_SUPPORT", "Participant/Trainee Support Costs", True),
    ("MATERIALS_SUPPLIES", "Materials and Supplies", True),
    ("PUBLICATION", "Publication Costs", True),
    ("CONSULTANT", "Consultant Services", True),
    ("ADP_COMPUTER", "ADP/Computer Services", True),
    ("SUBAWARD", "Subawards/Consortium/Contractual Costs", True),
    ("EQUIPMENT_RENTAL", "Equipment or Facility Rental/User Fees", True),
    ("ALTERATIONS", "Alterations and Renovations", True),
    ("OTHER_DIRECT", "Other Direct Costs", True),
    ("INDIRECT", "Indirect Costs (F&A)", False),
]


def literal(text):
    return "'" + str(text).replace("'", "''") + "'"


def allowed_value_id(group, code):
    """Opaque, deterministic, and short enough for any ID mapping."""
    return "AV-" + hashlib.sha1(f"{group}:{code}".encode()).hexdigest()[:12]


def label(code):
    return code.replace("_", " ")


def recommended_rows(schema, modules):
    """(group, code) pairs from every vocabulary column in core plus the declared modules, in file order."""
    seen, rows = set(), []
    tables = []
    for mod in schema["modules"]["core"].values():
        tables.extend(mod["tables"].values())
    om = schema["modules"]["optional"]
    for mkey in modules:
        if mkey not in om:
            raise SystemExit(f"FATAL: '{mkey}' is not a specified optional module (have: {', '.join(om)})")
        tables.extend(om[mkey]["tables"].values())
    for tdef in tables:
        for cdef in tdef["columns"].values():
            group = cdef.get("value_group")
            for code in cdef.get("recommended_values", []) if group else []:
                if (group, code) not in seen:
                    seen.add((group, code))
                    rows.append((group, code))
    return rows


def insert(syn, table, columns, values):
    q = syn["quote"]
    return (f"INSERT INTO {q(table)} (" + ", ".join(q(c) for c in columns) + ")\nVALUES (" + ", ".join(values) + ");")


def generate(schema, dialect, modules):
    if dialect not in DIALECTS:
        raise SystemExit(f"FATAL: unknown dialect '{dialect}' (have: {', '.join(DIALECTS)})")
    syn = DIALECTS[dialect]
    audit_cols = ["Created_At", "Updated_At", "Source_System", "Is_Active"]
    audit_vals = [syn["now"], syn["now"], literal(SOURCE_SYSTEM), syn["true"]]
    meta = schema["metadata"]
    out = [
        f"-- {meta['name']} {meta['version']} ({meta['released']}): {dialect} seed rows generated by scripts/generate_seed.py",
        "-- AllowedValues: one row per recommended code; Canonical_Value_Code equals the code. BudgetCategory: SF-424 R&R categories.",
        "-- Reference data only. Run after the DDL. Add institution-specific codes beside these rows.",
        "",
    ]
    rows = recommended_rows(schema, modules)
    out.append(f"-- AllowedValues: {len(rows)} rows" + (f" (core plus modules: {', '.join(modules)})" if modules else " (core)"))
    cols = ["AllowedValue_ID", "Value_Group", "Value_Code", "Value_Label", "Canonical_Value_Code"] + audit_cols
    for group, code in rows:
        out.append(insert(syn, "AllowedValues", cols,
                          [literal(allowed_value_id(group, code)), literal(group), literal(code), literal(label(code)), literal(code)] + audit_vals))
    out.append("")
    out.append(f"-- BudgetCategory: {len(BUDGET_CATEGORIES)} rows")
    cols = ["BudgetCategory_ID", "Category_Code", "Category_Name", "Category_Order", "Is_Direct_Cost"] + audit_cols
    for order, (code, name, direct) in enumerate(BUDGET_CATEGORIES, start=1):
        out.append(insert(syn, "BudgetCategory", cols,
                          [literal("BC-" + code), literal(code), literal(name), str(order), syn["true"] if direct else syn["false"]] + audit_vals))
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Generate seed rows for AllowedValues and BudgetCategory.")
    parser.add_argument("--schema", default=str(SCHEMA_PATH))
    parser.add_argument("--dialect", required=True, help="mysql or postgresql")
    parser.add_argument("--modules", default="", help="comma-separated optional modules whose vocabularies to include")
    parser.add_argument("--all-modules", action="store_true")
    args = parser.parse_args()
    schema = json.loads(Path(args.schema).read_text())
    modules = list(schema["modules"]["optional"]) if args.all_modules else [m for m in args.modules.split(",") if m]
    sys.stdout.write(generate(schema, args.dialect, modules))
    return 0


if __name__ == "__main__":
    sys.exit(main())
